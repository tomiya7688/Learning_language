# score は「点数」という意味の変数
# score に「点数を入力してください: 」と表示して入力された文字列を整数にして入れる
score = int(input("点数を入力してください: "))

# score が80以上なら、字下げした処理を実行する
if score >= 80:
    # 「とても良い結果です」とターミナルに表示する
    print("とても良い結果です")

# score が80未満で60以上なら、字下げした処理を実行する
elif score >= 60:
    # 「合格です」とターミナルに表示する
    print("合格です")

# score が80以上でも60以上でもない場合、字下げした処理を実行する
else:
    # 「もう一度挑戦しましょう」とターミナルに表示する
    print("もう一度挑戦しましょう")
