# HEIGHT はゲーム画面の縦幅（ピクセル）です。
# HEIGHT に 480 を入れる
HEIGHT = 480
# FPSはframes per second（1秒あたりの画面更新回数）の略。更新回数の上限です。
# FPS に 60 を入れる
FPS = 60
# PLAYER_X は自機を最初に置く中心位置です。画面左端からの距離をピクセルで表します。
# PLAYER_X に 320 を入れる
PLAYER_X = 320
# PLAYER_Y は自機を最初に置く中心位置です。画面上端からの距離をピクセルで表します。
# PLAYER_Y に 400 を入れる
PLAYER_Y = 400
# PLAYER_SPEEDはplayer（自機）のspeed（速さの指定）。1回の更新で横・縦それぞれに進む量（ピクセル）です。
# 縦と横の矢印を同時に押すと各方向へ5ピクセル進みます。斜め全体で5ピクセルという意味ではありません。
# PLAYER_SPEED に 5 を入れる
PLAYER_SPEED = 5
