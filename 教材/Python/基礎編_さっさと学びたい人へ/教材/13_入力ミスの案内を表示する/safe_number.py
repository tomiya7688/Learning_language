# 下の処理を試し、整数に変換できない場合は except の処理へ進む
try:
    # number は「数字」という意味
    # number に「数字を入力してください: 」と表示して入力された内容を整数にして入れる
    number = int(input("数字を入力してください: "))
# 入力を整数に変換できなかった場合、下の行を実行する
except ValueError:
    # 「数字を入力してください」と表示する
    print("数字を入力してください")
# 入力を整数に変換できた場合、下の行を実行する
else:
    # number に2を掛けた値を表示する
    print(number * 2)
