# number1 は「1つ目の数字」という意味
# number1 に8を入れる
number1 = 8
# number2 は「2つ目の数字」という意味
# number2 に2を入れる
number2 = 2

# 足し算
# 「足し算:」と number1 に number2 を足した値を表示する
print("足し算:", number1 + number2)
# 引き算
# 「引き算:」と number1 から number2 を引いた値を表示する
print("引き算:", number1 - number2)
# 掛け算
# 「掛け算:」と number1 に number2 を掛けた値を表示する
print("掛け算:", number1 * number2)
# 割り算
# 「割り算:」と number1 を number2 で割った値を表示する
print("割り算:", number1 / number2)
