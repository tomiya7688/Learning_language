# score は「点数」という意味
# score に「点数を入力してください: 」と表示して入力された内容を整数にして入れる
score = int(input("点数を入力してください: "))

# score が80以上なら、次の行を実行する
if score >= 80:
    # 「よくできました」と表示する
    print("よくできました")
# score が80未満で60以上なら、次の行を実行する
elif score >= 60:
    # 「合格です」と表示する
    print("合格です")
# score が60未満なら、次の行を実行する
else:
    # 「もう一度挑戦しましょう」と表示する
    print("もう一度挑戦しましょう")
