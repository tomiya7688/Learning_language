// printfとscanfを使うため、標準入出力の宣言を読み込む
#include <stdio.h>

// C言語のプログラムで最初に実行されるmain関数を書く
int main(void) {
    // 数当てゲームの答えを保存する
    int answer = 42;

    // 入力された予想を保存する
    int guess = 0;

    // 入力を促す文章を表示する
    printf("1から100までの数字を予想してください: ");

    // 入力された整数を1つ読み取り、guessの保存場所へ書き込む
    scanf("%d", &guess);

    // 予想と答えが同じか調べる
    if (guess == answer) {
        // 正解したことを表示する
        printf("正解です！\n");
    // 不正解で、予想が答えより大きいか調べる
    } else if (guess > answer) {
        // 答えを絞るためのヒントを表示する
        printf("もっと小さい数字です。\n");
    // 正解でも答えより大きくもない場合に実行する
    } else {
        // 答えを絞るためのヒントを表示する
        printf("もっと大きい数字です。\n");
    }

    // 正常終了を表す0をOSへ返す
    return 0;
}
